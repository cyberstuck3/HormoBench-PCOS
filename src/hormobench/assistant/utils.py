"""
Utility functions for the HormoBench Research Assistant.

JSON formatting, Markdown helpers, rough token counting, and safe
file I/O.  Nothing here touches benchmark results.
"""
from __future__ import annotations

import json
import textwrap
from pathlib import Path
from typing import Any


# ── JSON ────────────────────────────────────────────────────────────────

def pretty_json(obj: Any, max_depth: int | None = None) -> str:
    """Return a pretty-printed JSON string, optionally truncated."""
    return json.dumps(obj, indent=2, default=str)


def compact_json(obj: Any) -> str:
    """Single-line JSON for prompt injection where space matters."""
    return json.dumps(obj, separators=(",", ":"), default=str)


# ── Markdown ────────────────────────────────────────────────────────────

def md_heading(text: str, level: int = 2) -> str:
    return f"{'#' * level} {text}\n"


def md_section(heading: str, body: str, level: int = 2) -> str:
    """Heading + body with a trailing blank line."""
    return f"{md_heading(heading, level)}\n{body.strip()}\n\n"


def md_disclaimer() -> str:
    """Standard responsible-AI disclaimer block for reports."""
    return textwrap.dedent("""\
        ---

        > **Disclaimer.**  This report was generated by an AI assistant
        > interpreting benchmark outputs.  It is not a clinical assessment,
        > does not constitute medical advice, and must not be used for
        > diagnosis or treatment decisions.  All metrics are derived from
        > a single retrospective dataset of 541 patients from Kerala, India.
        > Prospective clinical validation is required before any deployment.
    """)


# ── Token estimation ───────────────────────────────────────────────────

def estimate_tokens(text: str) -> int:
    """Rough GPT-style token count (≈ 1 token per 4 chars in English).

    Good enough for budget guardrails; not a substitute for tiktoken.
    """
    return max(1, len(text) // 4)


# ── File helpers ────────────────────────────────────────────────────────

def safe_read(path: Path | str) -> str:
    """Read a text file, returning '' if it doesn't exist."""
    p = Path(path)
    return p.read_text() if p.exists() else ""


def safe_write(path: Path | str, content: str) -> Path:
    """Write *content* to *path*, creating parent dirs if needed."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content)
    return p
