"""
AI Report generator — produces ``docs/AI_REPORT.md``.

Each section is generated by sending the relevant benchmark evidence
(loaded read-only by :mod:`hormobench.assistant.loader`) together with
a section-specific system prompt to the OpenAI API.

The generator NEVER invents metrics.  Every claim the LLM makes must
come from the data injected into the prompt.
"""
from __future__ import annotations

from hormobench import DOCS
from hormobench.assistant.client import chat, get_client
from hormobench.assistant.loader import (
    load_all_outputs,
    format_test_metrics,
    format_shap_table,
    format_model_comparison,
)
from hormobench.assistant import prompts
from hormobench.assistant.utils import (
    md_section, md_disclaimer, pretty_json, safe_write,
)


# Section definitions: (heading, system_prompt, evidence_builder)
# evidence_builder is a callable(BenchmarkOutputs) → str

def _evidence_executive(o):
    return (
        "## Benchmark evidence\n\n"
        f"### Test metrics\n{format_test_metrics(o.rigor)}\n\n"
        f"### Model comparison\n{format_model_comparison(o.rigor)}\n\n"
        f"### Winner\n{o.baseline.get('best_model', '?')} "
        f"with params {o.baseline.get('best_params', {})}\n\n"
        f"### Calibration\n{pretty_json(o.rigor.get('calibration', {}))}\n"
    )


def _evidence_model_selection(o):
    return (
        f"### Winner: {o.baseline.get('best_model', '?')}\n\n"
        f"### CV results\n{format_model_comparison(o.rigor)}\n\n"
        f"### DeLong pairwise\n{pretty_json(o.rigor.get('delong', {}))}\n\n"
        f"### All models\n{pretty_json(o.baseline.get('all_models', {}))}\n"
    )


def _evidence_threshold(o):
    cfg = o.rigor.get("config", {})
    cm  = o.rigor.get("confusion_matrices", {})
    return (
        f"Threshold τ = {cfg.get('threshold', '?')}\n\n"
        f"### Confusion matrices\n{pretty_json(cm)}\n\n"
        f"### Recall\n{pretty_json(o.rigor['test_metrics'].get('recall', {}))}\n"
        f"### Precision\n{pretty_json(o.rigor['test_metrics'].get('precision', {}))}\n"
        f"### Specificity\n{pretty_json(o.rigor['test_metrics'].get('specificity', {}))}\n"
    )


def _evidence_shap(o):
    return (
        f"### SHAP feature importance (top 15)\n"
        f"{format_shap_table(o.shap_features)}\n"
    )


def _evidence_calibration(o):
    return (
        f"### Calibration\n{pretty_json(o.rigor.get('calibration', {}))}\n\n"
        f"### Brier score\n{pretty_json(o.rigor['test_metrics'].get('brier', {}))}\n"
    )


def _evidence_clinical(o):
    return (
        f"### Test metrics\n{format_test_metrics(o.rigor)}\n\n"
        f"### Threshold\n{o.rigor.get('config', {}).get('threshold', '?')}\n\n"
        f"### Confusion matrices\n{pretty_json(o.rigor.get('confusion_matrices', {}))}\n"
    )


def _evidence_limitations(o):
    return (
        f"### Test metrics\n"
        f"{format_test_metrics(o.rigor)}\n\n"
        f"### SHAP Top Features\n"
        f"{format_shap_table(o.shap_features, top_n=5)}\n"
    )


def _evidence_future(o):
    return _evidence_limitations(o)


def _evidence_responsible_ai(o):
    return (
        f"### Winner\n"
        f"{o.baseline.get('best_model', '?')}\n\n"
        f"### Test metrics\n"
        f"{format_test_metrics(o.rigor)}\n"
    )


_SECTIONS = [
    ("Executive Summary",       prompts.REPORT_EXECUTIVE_SUMMARY,     _evidence_executive),
    ("Model Selection",         prompts.REPORT_MODEL_SELECTION,        _evidence_model_selection),
    ("Threshold Analysis",      prompts.REPORT_THRESHOLD_ANALYSIS,     _evidence_threshold),
    ("SHAP Interpretation",     prompts.REPORT_SHAP_INTERPRETATION,    _evidence_shap),
    ("Calibration Analysis",    prompts.REPORT_CALIBRATION,            _evidence_calibration),
    ("Clinical Interpretation", prompts.REPORT_CLINICAL_INTERPRETATION, _evidence_clinical),
    ("Limitations",             prompts.REPORT_LIMITATIONS,            _evidence_limitations),
    ("Future Work",             prompts.REPORT_FUTURE_WORK,            _evidence_future),
    ("Responsible AI",          prompts.REPORT_RESPONSIBLE_AI,         _evidence_responsible_ai),
]

GROUNDING_RULES = """
You are writing a scientific benchmark report.

IMPORTANT RULES:

1. Use ONLY facts explicitly present in the supplied Benchmark evidence.

2. Never use external medical knowledge.

3. Never use prior knowledge about PCOS.

4. Never infer missing information.

5. If information is unavailable, explicitly write:

   "This information is not available in the benchmark artefacts."

6. Never invent:

- hospitals
- countries
- demographics
- dataset characteristics
- study design
- clinical guidelines

unless they appear in the Benchmark evidence.

7. Clearly distinguish observations from interpretations.

8. Never contradict any metric provided.

9. Every statement must be supported by the supplied Benchmark evidence.
"""

def generate_report(*, verbose: bool = True) -> str:
    """Generate the full AI report and write it to ``docs/AI_REPORT.md``.

    Returns the Markdown string.
    """
    client = get_client()
    outputs = load_all_outputs()

    parts = [
        "# HormoBench-PCOS — AI-Generated Research Report\n\n"
        "*This report was generated by the HormoBench Research Assistant "
        "using the OpenAI API.  Every claim is grounded in benchmark "
        "artefacts produced by `python scripts/benchmark.py`.  "
        "This is NOT a clinical assessment.*\n\n"
        "---\n\n"
    ]

    for heading, system_prompt, evidence_fn in _SECTIONS:
        if verbose:
            print(f"  Generating section: {heading} …")
        evidence = evidence_fn(outputs)
        body = chat(
            system=GROUNDING_RULES + "\n\n" + system_prompt,
            user=f"""
Using ONLY the benchmark evidence below, write the requested report section.

Do not use outside knowledge.

Do not infer missing information.

If a fact is unavailable, explicitly state:

"This information is not available in the benchmark artefacts."

Benchmark evidence:

{evidence}
""",
            client=client,
            max_tokens=2048,
        )
        parts.append(md_section(heading, body))

    parts.append(md_disclaimer())

    report = "".join(parts)
    out_path = safe_write(DOCS / "AI_REPORT.md", report)
    if verbose:
        print(f"\n✓ Report written → {out_path}")
    return report
